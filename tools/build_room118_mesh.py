#!/usr/bin/env python3
"""Generate the ROOM118 reconstruction mesh; requires no proprietary images.

Coordinates are in RE1 room units (negative Y is up). Wall positions are the
inner faces of ROOM1180.RDT's blocking rectangles at 0x188. The chest hinge is
the omodel_set at 0x2D4: (6320, -1410, 1770), yaw 0xC00. Its shipped TMD spans
local X=0..1440 and Z=-1080..1080. Its moving lid remains game-owned.

Ceiling height, door height and decorative furniture are visual estimates
against RC1180/RC1181, not recovered original environment geometry. Materials
use the synthetic validation atlas and vertex-lit plaster. Lighting is an
authored approximation from the reference images. Run from any directory.
"""
import argparse
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TILES = {
    "floor": (0, .5, .25, 1), "wall": (.25, .5, .5, 1),
    "ceiling": (.5, .5, .75, 1), "door": (.75, .5, 1, 1),
    "wood": (0, 0, .25, .5), "metal": (.25, 0, .5, .5),
}


def illumination(point):
    """Authored diffuse bake estimated from RC1180/1, not recovered RDT lights."""
    x, y, z = point
    # A downward pool widens below the wall lamp; ceiling stays in shadow.
    drop = max(0, y + 4200)
    width = 550 + drop * .48
    pool = math.exp(-((x-4800)/width)**2 - ((z-2050)/3200)**2)
    pool *= min(1, max(0, (y+4350)/450))
    bounce = math.exp(-((z-7500)/2600)**2 - ((y+1700)/2600)**2)
    return tuple(min(1, ambient + strength*pool + .16*bounce)
                 for ambient, strength in ((.20,.42),(.24,.55),(.30,.68)))


class Mesh:
    def __init__(self):
        self.lines = ["# Generated by tools/build_room118_mesh.py; room-space units.",
                      "# Static chest body only: the original TMD supplies its moving lid.",
                      "mtllib room1180.mtl"]
        self.vertices = 0
        self.texcoords = 0

    def face(self, points, tile="wall", material="room"):
        if tile == "wall" and material == "room":
            # Sample the light pool densely enough to interpolate smoothly.
            a, b, c, d = points
            def point(u, v):
                return tuple((1-u)*(1-v)*a[k] + (1-u)*v*b[k] +
                             u*v*c[k] + u*(1-v)*d[k] for k in range(3))
            for iu in range(12):
                for iv in range(12):
                    u, v = iu/12, iv/12
                    self.emit_face([point(u,v), point(u,v+1/12),
                                    point(u+1/12,v+1/12), point(u+1/12,v)],
                                   tile, "plaster", [(u,v),(u,v+1/12),(u+1/12,v+1/12),(u+1/12,v)])
        else:
            self.emit_face(points, tile, material)

    def emit_face(self, points, tile, material, uv=None):
        u0, v0, u1, v1 = TILES[tile]
        if uv is None:
            uv = [(u0, v0), (u0, v1), (u1, v1), (u1, v0)]
        refs = []
        for index, point in enumerate(points):
            self.vertices += 1
            self.texcoords += 1
            color = (1, 1, 1) if material == "paper" else illumination(point)
            self.lines.append("v " + " ".join(f"{v:.4f}" for v in (*point, *color)))
            self.lines.append("vt %.6f %.6f" % uv[index])
            refs.append(f"{self.vertices}/{self.texcoords}")
        self.lines.extend([f"usemtl {material}", "f " + " ".join(refs)])

    def box(self, name, lo, hi, tile="wood", material="room", top=True, omit=()):
        self.lines.append("o " + name)
        x0, y0, z0 = lo
        x1, y1, z1 = hi
        # y0 is the upper (negative) height, y1 the bottom height.
        if top:
            self.face([(x0,y0,z0),(x0,y0,z1),(x1,y0,z1),(x1,y0,z0)], tile, material)
        # Grounded solids need no underside coplanar with the room floor.
        if y1 != 0:
            self.face([(x0,y1,z0),(x1,y1,z0),(x1,y1,z1),(x0,y1,z1)], tile, material)
        if "z0" not in omit:
            self.face([(x0,y1,z0),(x0,y0,z0),(x1,y0,z0),(x1,y1,z0)], tile, material)
        if "x1" not in omit:
            self.face([(x1,y1,z0),(x1,y0,z0),(x1,y0,z1),(x1,y1,z1)], tile, material)
        if "z1" not in omit:
            self.face([(x1,y1,z1),(x1,y0,z1),(x0,y0,z1),(x0,y1,z1)], tile, material)
        if "x0" not in omit:
            self.face([(x0,y1,z1),(x0,y0,z1),(x0,y0,z0),(x0,y1,z0)], tile, material)

    def cylinder(self, name, x, z, radius, upper, lower, material="room"):
        self.lines.append("o " + name)
        ring = [(x + radius*math.cos(i*math.tau/12),
                 z + radius*math.sin(i*math.tau/12)) for i in range(12)]
        for i, (a, b) in enumerate(ring):
            c, d = ring[(i+1) % len(ring)]
            self.face([(a,lower,b),(a,upper,b),(c,upper,d),(c,lower,d)], "metal", material)
            self.face([(x,upper,z),(a,upper,b),(c,upper,d)], "metal", material)


def build():
    mesh = Mesh()
    x0, x1, z0, z1, ceiling = 1854, 7344, 1944, 8948, -6000
    # Four atlas panels across the room produce sixteen narrow boards.
    # U runs across X, keeping the board grain parallel to the room's Z axis.
    for name, y, tile in (("floor", 0, "floor"),
                          ("ceiling", ceiling, "ceiling")):
        mesh.lines.append("o " + name)
        for ix in range(4):
            for iz in range(4):
                xa, xb = x0+(x1-x0)*ix/4, x0+(x1-x0)*(ix+1)/4
                za, zb = z0+(z1-z0)*iz/4, z0+(z1-z0)*(iz+1)/4
                mesh.face([(xa,y,za),(xa,y,zb),(xb,y,zb),(xb,y,za)], tile)
    mesh.lines.append("o walls")
    mesh.face([(x0,0,z0),(x0,ceiling,z0),(x1,ceiling,z0),(x1,0,z0)])
    mesh.face([(x0,0,z0),(x0,0,z1),(x0,ceiling,z1),(x0,ceiling,z0)])
    mesh.face([(x1,0,z0),(x1,ceiling,z0),(x1,ceiling,z1),(x1,0,z1)])
    # Low skirting boards visible at the floor/wall junction in both views.
    mesh.box("skirting_left", (x0,-150,z0), (x0+45,0,z1), material="trim", omit=("x0",))
    mesh.box("skirting_right", (x1-45,-150,z0), (x1,0,z1), material="trim", omit=("x1",))
    mesh.box("skirting_chest_end", (x0,-150,z0), (x1,0,z0+45), material="trim", omit=("z0",))
    mesh.lines.append("g door_end")
    for a, b in [(x0,5600),(6800,x1)]:
        mesh.face([(a,0,z1),(a,ceiling,z1),(b,ceiling,z1),(b,0,z1)])
    for a, b in ((x0,5600),(6800,x1)):
        mesh.box("skirting_door_end", (a,-150,z1-45), (b,0,z1), material="trim", omit=("z1",))
    mesh.face([(5600,-3300,z1),(5600,ceiling,z1),(6800,ceiling,z1),(6800,-3300,z1)])
    mesh.lines.append("o door")
    mesh.face([(5600,0,z1-10),(6800,0,z1-10),(6800,-3300,z1-10),(5600,-3300,z1-10)], "door")
    for x in (5520, 6800):
        mesh.box("door_jamb", (x,-3400,z1-70), (x+80,0,z1), material="trim")
    mesh.box("door_lintel", (5520,-3400,z1-70), (6880,-3300,z1), material="trim")
    mesh.lines.append("g")
    for z in (2450,4450,6450,8450):
        mesh.box("ceiling_beam", (x0,ceiling,z), (x1,ceiling+150,z+130), "ceiling", "trim")

    # Body follows the original lid, including the part embedded in the wall.
    mesh.box("chest_body", (5240,-1410,1770), (7400,0,3210), material="trunk", top=False)
    mesh.box("chest_inside", (5300,-500,1830), (7340,-490,3150), material="trim")
    for x in (5500,7100):
        mesh.box("chest_front_band", (x,-1410,3210), (x+65,0,3220), material="trim")
    # Static frame stays below the moving lid's hinge height.
    for y in (-1370, -100):
        mesh.box("chest_front_rail", (5240,y,3210), (7400,y+70,3240), material="iron")
        for x in (5240,7370):
            mesh.box("chest_side_rail", (x,y,1770), (x+30,y+70,3210), material="iron")
    for x in (5500,7100):
        for y in (-1220,-720,-180):
            mesh.box("chest_rivet", (x+18,y,3221), (x+47,y+29,3250), material="brass")
    # The front carrying handle has an open center, not a painted rectangle.
    mesh.box("chest_handle_bar", (6100,-740,3270), (6540,-695,3310), material="iron")
    for x in (6100,6500):
        mesh.box("chest_handle_mount", (x,-850,3210), (x+40,-695,3310), material="iron")
    mesh.box("chest_lock", (6270,-1300,3210), (6380,-1080,3240), material="brass")
    mesh.cylinder("barrel", 2400, 2300, 520, -1500, 0)
    for y in (-1250,-380):
        mesh.cylinder("barrel_hoop", 2400, 2300, 532, y, y+85, "trim")
    mesh.box("crate_back", (3300,-760,1944), (4200,0,2682))
    mesh.box("crate_front", (2850,-650,2550), (3550,0,3210))

    mesh.lines.append("g door_end")
    mesh.cylinder("table_foot", 2500, 8500, 330, -100, 0, "trim")
    mesh.cylinder("table_stem", 2500, 8500, 65, -1480, -100, "trim")
    mesh.cylinder("table_top", 2500, 8500, 450, -1550, -1480, "trim")
    mesh.box("typewriter_base", (2200,-1640,8240), (2790,-1550,8700), material="enamel")
    mesh.box("typewriter_carriage", (2220,-1770,8510), (2770,-1640,8690), material="enamel")
    # Small geometry survives close inspection from a future movable camera.
    # Key layout is an approximation; the background does not resolve glyphs.
    for row in range(3):
        for column in range(10):
            x = 2240 + column*48 + (row % 2)*12
            z = 8270 + row*65
            mesh.cylinder("typewriter_key", x, z, 17, -1665-row*12,
                          -1640, "keycap")
    mesh.box("typewriter_spacebar", (2340,-1665,8220), (2630,-1640,8245), material="keycap")
    mesh.box("typewriter_platen", (2200,-1800,8590), (2800,-1745,8660), material="trim")
    for x in (2160,2800):
        mesh.box("typewriter_platen_knob", (x,-1808,8580), (x+40,-1737,8670), material="iron")
    mesh.box("typewriter_return_lever", (2160,-1795,8540), (2250,-1775,8600), material="iron")
    mesh.lines.append("o typewriter_paper")
    mesh.face([(2310,-1730,8540),(2310,-2100,8580),(2660,-2100,8580),(2660,-1730,8540)], material="paper")
    mesh.lines.append("g")
    mesh.box("wall_lamp", (4700,-4300,z0+10), (4900,-4210,z0+120), material="trim")
    mesh.box("wall_lamp_bulb", (4740,-4210,z0+30), (4860,-4170,z0+100), material="paper")
    return "\n".join(mesh.lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Write one mesh here; default emits both character variants")
    args = parser.parse_args()
    outputs = [args.output] if args.output else [
        ROOT / f"tests/fixtures/room3d/Stage1/room118{variant}.obj" for variant in (0, 1)]
    mesh = build()
    for output in outputs:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(mesh, encoding="ascii")
        print(output)


if __name__ == "__main__":
    main()
