"""Retouch generated room OBJ groups without inference or changes to the source export."""

import argparse
import hashlib
import html
import json
import math
import shutil
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from room3d_preview import render


def read_mesh(path):
    vertices, uvs, faces, libraries = [], [], [], []
    group, material = "ungrouped", ""
    for line in path.read_text().splitlines():
        words = line.split("#", 1)[0].split()
        if not words:
            continue
        kind, args = words[0], words[1:]
        if kind == "v":
            vertices.append(list(map(float, args)))
        elif kind == "vt":
            uvs.append(args)
        elif kind == "mtllib":
            libraries.append(" ".join(args))
        elif kind == "g":
            if len(args) != 1:
                raise ValueError("Retouch expects one group per face, as generated by the batcher")
            group = args[0]
        elif kind == "usemtl":
            material = " ".join(args)
        elif kind == "f":
            refs = []
            for item in args:
                fields = item.split("/")
                if len(fields) > 2 and fields[2]:
                    raise ValueError("Explicit normals are unsupported; use the batcher's generated OBJ")
                vi = int(fields[0])
                vi = vi - 1 if vi > 0 else len(vertices) + vi
                ti = None
                if len(fields) > 1 and fields[1]:
                    ti = int(fields[1])
                    ti = ti - 1 if ti > 0 else len(uvs) + ti
                if not 0 <= vi < len(vertices) or (ti is not None and not 0 <= ti < len(uvs)):
                    raise ValueError("Invalid OBJ index")
                refs.append((vi, ti))
            faces.append((group, material, refs))
    return vertices, uvs, faces, libraries


def catalog(mesh):
    vertices, _, faces, _ = mesh
    groups = {}
    for group, _, refs in faces:
        groups.setdefault(group, set()).update(vi for vi, _ in refs)
    result = {}
    for group, indices in sorted(groups.items()):
        points = np.array([vertices[i][:3] for i in indices])
        low, high = points.min(axis=0), points.max(axis=0)
        result[group] = {"min": low.tolist(), "max": high.tolist(),
                         "pivot": ((low + high) / 2).tolist()}
    return result


def transforms(edits, groups):
    if not isinstance(edits, dict) or set(edits) - groups.keys():
        raise ValueError("Edits must map existing group names to transforms")
    result = {}
    for group, options in edits.items():
        if not isinstance(options, dict) or set(options) - {"translate", "scale", "yaw", "pivot", "hide"}:
            raise ValueError(f"Unknown transform option for {group}")
        vectors = {}
        for key, default in (("translate", [0, 0, 0]), ("scale", [1, 1, 1]),
                             ("pivot", groups[group]["pivot"])):
            value = np.asarray(options.get(key, default), dtype=float)
            if value.shape != (3,) or not np.isfinite(value).all():
                raise ValueError(f"{group}.{key} must be three finite numbers")
            vectors[key] = value
        if np.any(vectors["scale"] <= 0):
            raise ValueError("Scale must be positive; mirroring would reverse face winding")
        yaw = float(options.get("yaw", 0))
        if not math.isfinite(yaw) or not isinstance(options.get("hide", False), bool):
            raise ValueError("Yaw must be finite and hide must be boolean")
        angle = math.radians(yaw)
        c, s = math.cos(angle), math.sin(angle)
        vectors["rotation"] = np.array([[c, 0, -s], [0, 1, 0], [s, 0, c]])
        vectors["hide"] = options.get("hide", False)
        result[group] = vectors
    return result


def write_mesh(mesh, edits, target):
    vertices, uvs, faces, libraries = mesh
    operations = transforms(edits, catalog(mesh))
    lines = ["# Manual retouch; original projected textures retained."]
    lines.extend("mtllib " + name for name in libraries)
    lines.extend("vt " + " ".join(uv) for uv in uvs)
    count = 0
    for group, material, refs in faces:
        operation = operations.get(group)
        if operation is not None and operation["hide"]:
            continue
        lines.extend(["g " + group, "usemtl " + material])
        mapped = []
        for vi, ti in refs:
            vertex = vertices[vi]
            point = np.array(vertex[:3])
            if operation is not None:
                point = (operation["rotation"] @ ((point - operation["pivot"]) * operation["scale"])
                         + operation["pivot"] + operation["translate"])
            lines.append("v " + " ".join(format(float(v), ".12g") for v in [*point, *vertex[3:]]))
            count += 1
            mapped.append(str(count) + (f"/{ti + 1}" if ti is not None else ""))
        lines.append("f " + " ".join(mapped))
    target.write_text("\n".join(lines) + "\n")


def local_file(root, name):
    path = (root / name).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError(f"Missing or non-local material dependency: {name}")
    return path


def appearance_context(room):
    """Carry semantic bake settings; edited OBJ remains the geometry authority."""
    inherited = room / 'retouch-appearance.json'
    if inherited.exists():
        return json.loads(inherited.read_text())
    original = room / 'assisted.json'
    if original.exists():
        return {'recipe': json.loads(original.read_text())['fitted_recipe'],
                'added_groups': [],
                'qualification': 'Appearance semantics only; primitive poses may precede edits. '
                                 'assisted.obj is authoritative for retouched geometry.'}
    return None


def reproject_appearance(room, out, survey, segmentation=None, depth=None):
    from room3d_additions import associate_fixture_masks
    from room3d_reconstruct import bake_projected

    images = [Image.open(room / f"camera{camera['index']}-original.png").convert('RGB')
              for camera in survey['cameras']]
    context = appearance_context(out)
    recipe = context['recipe']
    additions = context['added_groups']
    kinds = {f'primitive_{i}': item['kind'] for i, item in enumerate(recipe.get('primitives', []))}
    kinds.update({f"boundary_{b['index']}": 'wall' for b in survey['boundaries'] if b['flags'] & 0x100})
    kinds['floor'] = 'floor'
    kinds.update({s['group']: s['material'] for s in recipe.get('structural_surfaces', [])
                  if s['material'] in ('wall', 'floor', 'ceiling')})
    kinds.update({item['group']: item['kind'] for item in additions})
    interpreted = {f'primitive_{i}' for i, item in enumerate(recipe.get('primitives', []))
                   if item.get('interpretation')}
    interpreted.update(item['group'] for item in additions)
    fixture_observations = {
        f'primitive_{i}': item.get('evidence', {}).get('shared_observations', [])
        for i, item in enumerate(recipe.get('primitives', []))
        if item.get('interpretation') and item.get('kind') == 'lamp'
    } if recipe.get('local_fixture_appearance', False) else None
    masks = observations = None
    if segmentation is not None:
        from room3d_segment import load_masks

        masks = load_masks(segmentation, survey, images)
    added_sources = associate_fixture_masks(out / 'assisted.obj', survey, masks,
                                           [item['group'] for item in additions if item['kind'] == 'lamp'])
    fixture_observations = {**(fixture_observations or {}), **added_sources}
    if depth is not None:
        from room3d_refine import load_depth

        observations = load_depth(depth, room / 'survey.json', survey, images)
    from room3d_texture_ownership import reconstructed_sources

    report = bake_projected(out / 'assisted.obj', survey, images, out / 'reprojected.obj',
                            segments=masks, group_kinds=kinds, observed_depths=observations,
                            interpreted_groups=interpreted,
                            fixture_observations=fixture_observations,
                            reconstructed_observations=reconstructed_sources(recipe),
                            foreground_fixture_guard=recipe.get('foreground_fixture_guard', False),
                            fixture_core_appearance=recipe.get('fixture_core_appearance', False),
                            preserve_fixture_appearance=True)
    report['added_fixture_associations'] = added_sources
    (out / 'reprojected.obj').replace(out / 'assisted.obj')
    sidecar = out / 'reprojected.cameras'
    if sidecar.exists():
        sidecar.replace(out / 'assisted.cameras')
    (out / 'reprojection.json').write_text(json.dumps(report, indent=2) + '\n')


def run(room, edits, out, reproject=False, segmentation=None, depth=None, additions=None):
    from room3d_additions import LIBRARY, append_objects, material_library_text

    if out.exists():
        raise ValueError("Choose a new output directory to preserve previous variants")
    if out.resolve().is_relative_to(room.resolve()):
        raise ValueError("Keep retouches outside the automatic room output")
    source = room / "assisted.obj"
    mesh = read_mesh(source)
    # Validate all texture dependencies before creating the variant directory.
    dependencies = set()
    for name in mesh[3]:
        material = local_file(room, name)
        dependencies.add(material)
        for line in material.read_text().splitlines():
            words = line.split()
            if words and words[0] == "map_Kd":
                dependencies.add(local_file(room, " ".join(words[1:])))
    survey = json.loads((room / "survey.json").read_text())
    context = appearance_context(room)
    if reproject and context is None:
        raise ValueError('Reprojection needs original or inherited appearance semantics')
    mesh, generated = append_objects(mesh, [] if additions is None else additions)
    transforms(edits, catalog(mesh))
    if generated:
        for path in dependencies:
            if (path.relative_to(room.resolve()).as_posix() == LIBRARY
                    and path.read_text() != material_library_text()):
                raise ValueError('Reserved additions materials were customized; preserve them in a separate variant')
    out.mkdir(parents=True)
    for path in dependencies:
        target = out / path.relative_to(room.resolve())
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
    if generated:
        (out / LIBRARY).write_text(material_library_text())
    target = out / "assisted.obj"
    write_mesh(mesh, edits, target)
    sidecar = source.with_suffix(".cameras")
    if sidecar.exists():
        shutil.copy2(sidecar, target.with_suffix(".cameras"))
    shutil.copy2(room / "survey.json", out / "survey.json")
    if context is not None:
        context['added_groups'].extend({'group': item['group'], 'kind': item['kind']}
                                       for item in generated)
        (out / 'retouch-appearance.json').write_text(json.dumps(context, indent=2) + '\n')
    if reproject:
        reproject_appearance(room, out, survey, segmentation, depth)
    record = {"source": str(source.resolve()),
              "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
              "edits": edits, "groups": catalog(mesh),
              "additions": generated,
              "appearance": "reprojected" if reproject else "original_uvs_preserved",
              "status": "manual_visual_retouch_gameplay_unchanged"}
    (out / "retouch.json").write_text(json.dumps(record, indent=2) + "\n")
    appearance = ('Textures reprojected onto edited geometry; unseen appearance remains estimated.'
                  if reproject else 'Textures move with geometry; newly exposed areas may lack appearance.')
    if generated:
        appearance += ' Added parametric objects are manual estimates; neutral gray marks untextured additions.'
    rows = [(f"<h1>Room retouch</h1><p>Original background / automatic / retouched. {appearance} "
            "Gameplay collisions are unchanged.</p><a href='retouch.json'>Saved corrections</a>")]
    for camera in survey["cameras"]:
        index = camera["index"]
        original = Image.open(room / f"camera{index}-original.png").convert("RGB")
        before, _ = render(source, camera)
        after, _ = render(target, camera)
        sheet = Image.new("RGB", (960, 264), (20, 20, 20))
        draw = ImageDraw.Draw(sheet)
        for i, (label, image) in enumerate((("Original", original), ("Automatic", before), ("Retouched", after))):
            draw.text((i * 320 + 5, 5), label, fill="white")
            sheet.paste(image, (i * 320, 24))
        name = f"camera{index}.png"
        sheet.save(out / name)
        original.save(out / f"camera{index}-original.png")
        rows.append(f"<h2>Camera {index}</h2><img width='960' src='{html.escape(name)}'>")
    (out / "index.html").write_text("<!doctype html><meta charset='utf-8'><title>Room retouch</title>"
                                    "<style>body{background:#171b22;color:white;font:16px system-ui}"
                                    "img{max-width:100%}a{color:#8cf}</style>" + "".join(rows))
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--room", type=Path, required=True)
    parser.add_argument("--list", action="store_true", help="List editable groups and their bounds")
    parser.add_argument("--edits", type=Path, help="JSON mapping group names to transforms")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--additions", type=Path, help="JSON list of parametric objects to insert")
    parser.add_argument("--reproject", action="store_true", help="Rebake appearance after edits without rerunning models")
    parser.add_argument("--segmentation", type=Path, help="Existing SAM directory for this room")
    parser.add_argument("--depth", type=Path, help="Existing DA3 directory for this room")
    args = parser.parse_args()
    if args.list:
        print(json.dumps(catalog(read_mesh(args.room / "assisted.obj")), indent=2))
        return
    if not (args.edits or args.additions) or not args.out:
        parser.error("--out and either --edits or --additions are required unless using --list")
    if (args.segmentation or args.depth) and not args.reproject:
        parser.error("--segmentation and --depth require --reproject")
    run(args.room, json.loads(args.edits.read_text()) if args.edits else {}, args.out,
        args.reproject, args.segmentation, args.depth,
        json.loads(args.additions.read_text()) if args.additions else None)
    print(args.out / "index.html")


if __name__ == "__main__":
    main()
